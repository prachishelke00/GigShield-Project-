const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("==================================================");
  console.log("   GIGSHIELD 2.0 - DUAL CONTRACT DEPLOYMENT       ");
  console.log("   MST Testnet (Chain ID: 91562037)              ");
  console.log("==================================================");

  const [deployer] = await hre.ethers.getSigners();
  console.log("Deployer / Initial Verifier Address:", deployer.address);

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log("Deployer tMSTC balance for gas:", hre.ethers.formatEther(balance), "tMSTC");

  // 1. Deploy GigShieldToken (GST ERC-20)
  console.log("\n[1/3] Deploying GigShieldToken (GST)...");
  const GigShieldToken = await hre.ethers.getContractFactory("GigShieldToken");
  const gstToken = await GigShieldToken.deploy();
  await gstToken.waitForDeployment();
  const tokenAddress = await gstToken.getAddress();
  console.log("✓ GigShieldToken deployed at:", tokenAddress);

  // 2. Deploy GigShield Main Insurance Contract
  console.log("\n[2/3] Deploying GigShield Insurance Protocol...");
  const GigShield = await hre.ethers.getContractFactory("GigShield");
  const gigShield = await GigShield.deploy(tokenAddress, deployer.address);
  await gigShield.waitForDeployment();
  const gigShieldAddress = await gigShield.getAddress();
  console.log("✓ GigShield deployed at:", gigShieldAddress);

  // 3. Seed Initial Liquidity Pool with GST Tokens
  console.log("\n[3/3] Seeding Initial Payout Pool with 10,000 GST...");
  try {
    const seedAmount = hre.ethers.parseEther("10000");
    const approveTx = await gstToken.approve(gigShieldAddress, seedAmount);
    await approveTx.wait();
    const fundTx = await gigShield.fundPayoutPool(seedAmount);
    await fundTx.wait();
    console.log("✓ Initial insurance payout pool successfully seeded with 10,000 GST!");
  } catch (poolErr) {
    console.warn("Notice: Pool auto-funding skipped or pending:", poolErr.message);
  }

  // 4. Update Frontend Configuration
  const frontendConfigPath = path.join(__dirname, "..", "frontend", "config.js");
  const gigShieldArtifact = await hre.artifacts.readArtifact("GigShield");
  const tokenArtifact = await hre.artifacts.readArtifact("GigShieldToken");

  const configContent = `// GigShield Web3 Configuration (Auto-generated by deploy.js)
// MST Blockchain Testnet

window.GIGSHIELD_CONFIG = {
  gigShieldAddress: "${gigShieldAddress}",
  gstTokenAddress: "${tokenAddress}",
  chainId: 91562037,
  chainIdHex: "0x5752035",
  chainName: "MST Testnet",
  rpcUrl: "https://testnetrpc.mstblockchain.com",
  explorerUrl: "https://testnet.mstscan.com",
  faucetUrl: "https://faucet.mstblockchain.com/",
  backendUrl: "http://localhost:3001",
  gigShieldAbi: ${JSON.stringify(gigShieldArtifact.abi, null, 2)},
  gstTokenAbi: ${JSON.stringify(tokenArtifact.abi, null, 2)}
};
`;

  fs.writeFileSync(frontendConfigPath, configContent);
  console.log("\n✓ Updated frontend/config.js with addresses and complete ABIs.");

  console.log("\n==================================================");
  console.log("             DEPLOYMENT COMPLETE                  ");
  console.log("==================================================");
  console.log("GST Token Address: ", tokenAddress);
  console.log("GigShield Address: ", gigShieldAddress);
  console.log("Explorer Link (GST): https://testnet.mstscan.com/address/" + tokenAddress);
  console.log("Explorer Link (DApp): https://testnet.mstscan.com/address/" + gigShieldAddress);
  console.log("==================================================");
}

main().catch((error) => {
  console.error("Deployment failed:", error);
  process.exitCode = 1;
});
